function body(name) {
  const alias = SET.aliases && SET.aliases[name]
  if (alias && Object.keys(alias).some((k) => k !== "parent"))
    throw new Error(`Alias transformé non pris en charge : ${name}`)
  const icon = SET.icons[alias ? alias.parent : name]
  if (!icon) throw new Error(`Icône Lucide introuvable : ${name}`)
  if ((icon.width || SET.width || 24) !== 24)
    throw new Error(`Grille inattendue pour ${name}`)
  return icon.body.replace(/ stroke-width="2"/g, "").replace(/'/g, '"')
}

